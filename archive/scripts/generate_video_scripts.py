    with open(csv_file, mode='r', encoding='utf-8-sig') as f:
        reader = csv.DictReader(f)
        for row in reader:
            pid = row.get("Product ID")
            name = row.get("Product Name")
            category = row.get("Category")
            price = row.get("Price (THB)")
            commission = row.get("Commission Rate")
            url = row.get("Product URL")
            
            script_info = scripts_db.get(pid, {
                "hook": row.get("AI Video Hook / Concept", "รีวิวสินค้าขายดีกระแสแรง"),
                "voiceover": f"แนะนำ {name} สินค้าดีคุณภาพเยี่ยม สนใจกดสั่งซื้อที่ตะกร้าส้มได้เลย!",
                "visual_timeline": [
                    {"time": "0-3s", "action": "โชว์ตัวสินค้าและเขียนพาดหัวกระตุ้นความสนใจ"},
                    {"time": "3-15s", "action": "สาธิตการใช้งานและจุดเด่นหลักของสินค้า"},
                    {"time": "15-25s", "action": "ถือสินค้าคู่หน้ากล้องแล้วชี้บอกพิกัดกดซื้อในตะกร้าส้ม"}
                ]
            })
            
            output_data.append({
                "product_id": pid,
                "product_name": name,
                "category": category,
                "price_thb": price,
                "commission_rate": commission,
                "product_url": url,
                "ai_scripts": script_info
            })

    # Save to JSON
    json_output = "video_scripts_data.json"
    with open(json_output, 'w', encoding='utf-8') as f_json:
        json.dump(output_data, f_json, indent=4, ensure_ascii=False)
    print(f"Successfully generated {json_output} for system integration!")

    # Save to Markdown
    md_output = "video_scripts_catalog.md"
    with open(md_output, 'w', encoding='utf-8') as f_md:
        f_md.write("# 🎬 คลังสคริปต์วิดีโอปักตะกร้าส้ม Shopee อัตโนมัติ (Generated catalog)\n\n")
