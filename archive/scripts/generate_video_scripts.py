        for item in output_data:
            f_md.write(f"## 📦 {item['product_name']}\n")
            f_md.write(f"* **รหัสสินค้า (Product ID):** `{item['product_id']}`\n")
            f_md.write(f"* **ราคา:** `{item['price_thb']} บาท` | **ค่าคอมมิชชัน:** `{item['commission_rate']}`\n")
